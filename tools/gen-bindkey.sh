# Write a new BTHome bindkey to firmware/secrets.h (gitignored). Refuses if the file exists: the key
# in Home Assistant must match the key on the chip. The key goes to NVM3 through
# swd/provision-bindkey.tcl; the firmware never includes this file. An NVM3 erase (ERASE_NVM3,
# device erase, stock restore) deletes the key together with the counter mark, which restarts at
# 100: the old key must not be reused. Move the old file to dumps/secrets-<date>.h, then run this
# for a new key.
set -euo pipefail
cd "$(dirname "$0")/.."
F=firmware/secrets.h
if [ -e "$F" ]; then
  echo "$F exists; not overwritten" >&2
  exit 1
fi
git check-ignore -q "$F" || {
  echo "$F is not gitignored; refusing to write the key" >&2
  exit 1
}
umask 077
BYTES=$(od -An -tx1 -N16 /dev/urandom | tr -s ' \n' ' ' | sed 's/^ //; s/ $//')
{
  echo "// BTHome bindkey. Secret: never commit or upload this file. Generated by tools/gen-bindkey.sh."
  echo "#define BTHOME_BINDKEY { $(echo "$BYTES" | sed 's/\([0-9a-f][0-9a-f]\)/0x\1,/g; s/,$//; s/, */, /g') }"
} > "$F"
echo "wrote $F"
